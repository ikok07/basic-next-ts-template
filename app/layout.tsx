import type { Metadata } from "next";
import "./globals.css";
import {ReactNode} from "react";
import {getLocale, getMessages} from "next-intl/server";
import {NextIntlClientProvider} from "next-intl";
import AppStoreProvider from "@/app/_providers/AppStoreProvider";
import AppQueryClientProvider from "@/app/_providers/AppQueryClientProvider";
import {ToastContainer} from "react-toastify";
import {ClerkProvider} from "@clerk/nextjs";
import {bgBG, enUS} from "@clerk/localizations";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

type LayoutProps = {
    children: ReactNode
}

export default async function RootLayout({
  children,
}: Readonly<LayoutProps>) {
    const locale = await getLocale()
    const messages = await getMessages();

    return (
        <ClerkProvider
            localization={locale === "bg" ? bgBG : enUS}
            appearance={{
                variables: {
                    colorPrimary: "#825dff"
                },
                layout: {
                    logoImageUrl: "/logo.png",
                    privacyPageUrl: "/",
                },
                elements: {
                    logoImage: "h-[3rem] mb-3"
                }
            }}
        >
            <html lang={locale}>
            <NextIntlClientProvider messages={messages}>
                <AppStoreProvider>
                    <AppQueryClientProvider>
                        <body>
                        {children}
                        <ToastContainer />
                        </body>
                    </AppQueryClientProvider>
                </AppStoreProvider>
            </NextIntlClientProvider>
            </html>
        </ClerkProvider>
    );
}
